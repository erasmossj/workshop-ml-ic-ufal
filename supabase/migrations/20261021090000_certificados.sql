create table public.atividades_certificado (
  id smallint generated by default as identity primary key,
  dia date not null,
  minicurso_id smallint references public.minicursos (id), -- null = palestras da manhã
  titulo text not null check (char_length(titulo) between 1 and 120),
  minutos integer not null check (minutos between 0 and 1440),
  constraint atividade_unica unique nulls not distinct (dia, minicurso_id)
);

