-- Posição de um campo (Nome, CPF ou Horas) em pontos do PDF, origem no canto superior esquerdo.
create function public.campo_certificado(p_campo jsonb) returns jsonb
language plpgsql immutable set search_path = '' as $$
declare
  v_num numeric;
  v_chave text;
  v_limites constant jsonb := '{"pagina":[0,50],"x":[0,5000],"y":[0,5000],"largura":[10,5000],"tamanho":[6,72]}';
begin
  if jsonb_typeof(p_campo) is distinct from 'object' then
    raise exception 'CAMPOS_INVALIDOS';
  end if;
  for v_chave in select jsonb_object_keys(v_limites) loop
    if jsonb_typeof(p_campo -> v_chave) is distinct from 'number' then
      raise exception 'CAMPOS_INVALIDOS';
    end if;
    v_num := (p_campo ->> v_chave)::numeric;
    if v_num < (v_limites -> v_chave ->> 0)::numeric or v_num > (v_limites -> v_chave ->> 1)::numeric then
      raise exception 'CAMPOS_INVALIDOS';
    end if;
  end loop;
  if (p_campo ->> 'pagina')::numeric <> trunc((p_campo ->> 'pagina')::numeric)
     or coalesce(p_campo ->> 'alinhamento', '') not in ('esquerda', 'centro', 'direita')
     or coalesce(p_campo ->> 'fonte', '') not in ('helvetica', 'helvetica-negrito', 'times', 'times-negrito') then
    raise exception 'CAMPOS_INVALIDOS';
  end if;
  -- Guarda só as chaves conhecidas.
  return jsonb_build_object(
    'pagina', (p_campo ->> 'pagina')::integer, 'x', p_campo -> 'x', 'y', p_campo -> 'y',
    'largura', p_campo -> 'largura', 'tamanho', p_campo -> 'tamanho',
    'alinhamento', p_campo -> 'alinhamento', 'fonte', p_campo -> 'fonte');
end $$;

create function public.admin_obter_modelo_certificado() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.pode_administrar() then
    raise exception 'NAO_AUTORIZADO';
  end if;
  return (select jsonb_build_object('template_path', c.template_path, 'campos', c.campos,
                                    'atualizado_em', c.atualizado_em)
            from public.config_certificado c where c.id);
end $$;

create function public.admin_salvar_modelo_certificado(p_template_path text, p_campos jsonb) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.pode_administrar() then
    raise exception 'NAO_AUTORIZADO';
  end if;
  -- Nome gerado no navegador (UUID) e arquivo já enviado ao bucket privado.
  if coalesce(p_template_path, '') !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.pdf$'
     or not exists (select 1 from storage.objects o where o.bucket_id = 'certificados' and o.name = p_template_path) then
    raise exception 'MODELO_INVALIDO';
  end if;
  update public.config_certificado c
     set template_path = p_template_path,
         campos = jsonb_build_object(
           'nome', public.campo_certificado(p_campos -> 'nome'),
           'cpf', public.campo_certificado(p_campos -> 'cpf'),
           'horas', public.campo_certificado(p_campos -> 'horas')),
         atualizado_em = now()
   where c.id;
end $$;

