-- IC-ML 2026 — schema de inscrição (WML-24, WML-25 · ADR-003 · threat model S1).
-- Regras: RLS em todas as tabelas; anon/authenticated sem privilégio direto em tabelas;
-- todo acesso passa por funções SECURITY DEFINER com search_path vazio.

-- Nada criado daqui em diante herda privilégios para anon/authenticated.
alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated;
alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated;
alter default privileges for role postgres in schema public revoke execute on functions from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Tabelas
