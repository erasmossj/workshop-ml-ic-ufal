-- Certificados (WML-57..60 · ADR-002 · ADR-005).
-- Horas = carga das manhãs com presença (palestras) + carga das tardes de minicurso com presença.
-- O PDF não é guardado: o banco guarda a emissão (horas congeladas + código de validação) e a
-- Edge Function monta o PDF na hora sobre o modelo enviado pela organização.
-- CPF completo só sai por funções de servidor (service_role) usadas para montar o PDF.

-- ---------------------------------------------------------------------------
-- Carga horária (WML-57)
