create function public.cpf_valido(p_cpf text) returns boolean
language plpgsql immutable set search_path = '' as $$
declare
  d text := regexp_replace(coalesce(p_cpf, ''), '\D', '', 'g');
  soma integer;
  resto integer;
begin
  if length(d) <> 11 or d ~ '^(\d)\1{10}$' then
    return false;
  end if;
  for k in 9..10 loop
    soma := 0;
    for i in 1..k loop
      soma := soma + substr(d, i, 1)::integer * (k + 2 - i);
    end loop;
    resto := (soma * 10) % 11;
    if resto = 10 then resto := 0; end if;
    if resto <> substr(d, k + 1, 1)::integer then
      return false;
    end if;
  end loop;
  return true;
end $$;

-- ***.456.789-** (padrão gov.br). Única forma de o CPF sair do banco fora do certificado.
create function public.mascarar_cpf(p_cpf text) returns text
language sql immutable set search_path = '' as $$
  select case
    when p_cpf ~ '^[0-9]{11}$' then '***.' || substr(p_cpf, 4, 3) || '.' || substr(p_cpf, 7, 3) || '-**'
    else '***.***.***-**'
  end
$$;

create function public.pode_administrar() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(auth.jwt() ->> 'role' = 'service_role', false)
      or exists (
        select 1 from public.organizadores o where o.email = lower(auth.jwt() ->> 'email')
      )
$$;

-- ---------------------------------------------------------------------------
-- Inscrição (ADR-003): tudo em uma transação; a vaga é ocupada com UPDATE condicional.
-- Erros de negócio saem como SQLSTATE P0001 com a mensagem = código (mapeado na Edge Function).
-- ---------------------------------------------------------------------------

create function public.register_participant(
  p_nome text,
  p_cpf text,
  p_email text,
  p_instituicao text,
  p_minicursos smallint[],
  p_trabalho jsonb
) returns table (id_inscricao uuid, numero_inscricao text)
language plpgsql security definer set search_path = '' as $$
declare
  cfg public.config_evento;
  v_nome text := regexp_replace(btrim(coalesce(p_nome, '')), '\s+', ' ', 'g');
  v_cpf text := regexp_replace(coalesce(p_cpf, ''), '\D', '', 'g');
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_inst text := nullif(btrim(coalesce(p_instituicao, '')), '');
  v_id uuid;
  v_numero text;
  v_mc smallint;
  v_vagas integer;
begin
  select * into cfg from public.config_evento c where c.id;
  if not found or now() not between cfg.inscricoes_inicio and cfg.inscricoes_fim then
    raise exception 'INSCRICOES_FECHADAS';
  end if;

  if position(' ' in v_nome) = 0 or char_length(v_nome) > 120
     or v_nome ~ '[0-9<>{}\[\]\\/@#$%&*=+_|^~`"!?;:]' then
    raise exception 'NOME_INVALIDO';
  end if;
  if not public.cpf_valido(v_cpf) then
    raise exception 'CPF_INVALIDO';
  end if;
  if char_length(v_email) > 254 or v_email !~ '^[^\s@]+@[^\s@.]+(\.[^\s@.]+)+$' then
    raise exception 'EMAIL_INVALIDO';
  end if;

  begin
    insert into public.participantes (nome, cpf, email, instituicao)
    values (v_nome, v_cpf, v_email, v_inst)
    returning participantes.id, participantes.numero into v_id, v_numero;
  exception when unique_violation then
    raise exception 'EMAIL_JA_INSCRITO';
  end;

  foreach v_mc in array (select coalesce(array_agg(distinct x), '{}') from unnest(p_minicursos) x) loop
    select m.vagas into v_vagas from public.minicursos m where m.id = v_mc;
    if not found then
      raise exception 'MINICURSO_INEXISTENTE';
    end if;
    if v_vagas is null then
      raise exception 'MINICURSO_FECHADO';
    end if;
    -- Atômico: em concorrência, o segundo UPDATE reavalia a condição após o commit do primeiro.
    update public.minicursos m set ocupadas = m.ocupadas + 1
     where m.id = v_mc and m.ocupadas < m.vagas;
    if not found then
      raise exception 'MINICURSO_ESGOTADO';
    end if;
    begin
      insert into public.inscricoes_minicurso (participante_id, minicurso_id, cpf)
      values (v_id, v_mc, v_cpf);
    exception when unique_violation then
      raise exception 'CPF_JA_NO_MINICURSO';
    end;
  end loop;

  if p_trabalho is not null then
    if now() not between cfg.submissoes_inicio and cfg.submissoes_fim then
      raise exception 'SUBMISSOES_FECHADAS';
    end if;
    if coalesce((p_trabalho ->> 'premio')::boolean, false)
       and nullif(p_trabalho ->> 'nivel', '') is null then
      raise exception 'NIVEL_OBRIGATORIO';
    end if;
    begin
      insert into public.trabalhos (participante_id, titulo, autores, resumo, premio, nivel)
      values (
        v_id,
        btrim(p_trabalho ->> 'titulo'),
        btrim(p_trabalho ->> 'autores'),
        btrim(p_trabalho ->> 'resumo'),
        coalesce((p_trabalho ->> 'premio')::boolean, false),
        nullif(p_trabalho ->> 'nivel', '')::public.nivel_premio
      );
    exception when check_violation or not_null_violation or invalid_text_representation then
      raise exception 'TRABALHO_INVALIDO';
    end;
  end if;

  insert into public.email_outbox (participante_id, tipo) values (v_id, 'confirmacao');

  id_inscricao := v_id;
  numero_inscricao := v_numero;
  return next;
end $$;

-- Cancela a inscrição e libera as vagas na mesma transação (organização ou servidor).
create function public.cancel_registration(p_participante uuid) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.pode_administrar() then
    raise exception 'NAO_AUTORIZADO';
  end if;
  update public.minicursos m set ocupadas = m.ocupadas - 1
    from public.inscricoes_minicurso i
   where i.participante_id = p_participante and i.minicurso_id = m.id;
  delete from public.inscricoes_minicurso i where i.participante_id = p_participante;
  update public.participantes p set cancelada_em = now()
   where p.id = p_participante and p.cancelada_em is null;
end $$;

-- Pública: vagas restantes (sem dado pessoal).
create function public.vagas_publicas()
returns table (slug text, titulo text, vagas integer, restantes integer)
language sql stable security definer set search_path = '' as $$
  select m.slug, m.titulo, m.vagas,
         case when m.vagas is null then null else m.vagas - m.ocupadas end
    from public.minicursos m
   order by m.id
$$;

