-- Minutos do participante (0 se cancelado).
create function public.horas_participante(p_participante uuid) returns integer
language sql stable security definer set search_path = '' as $$
  select coalesce(sum(a.minutos), 0)::integer
    from public.presencas pr
    join public.atividades_certificado a
      on a.dia = pr.dia and a.minicurso_id is not distinct from pr.minicurso_id
    join public.participantes p on p.id = pr.participante_id
   where pr.participante_id = p_participante and p.cancelada_em is null
$$;

create function public.admin_listar_atividades() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.pode_administrar() then
    raise exception 'NAO_AUTORIZADO';
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', a.id, 'dia', a.dia, 'tipo', case when a.minicurso_id is null then 'palestras' else 'minicurso' end,
             'minicurso', m.titulo, 'titulo', a.titulo, 'minutos', a.minutos)
           order by a.dia, a.minicurso_id nulls first)
      from public.atividades_certificado a
      left join public.minicursos m on m.id = a.minicurso_id), '[]'::jsonb);
end $$;

create function public.admin_definir_carga(p_id smallint, p_titulo text, p_minutos integer) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_titulo text := btrim(coalesce(p_titulo, ''));
begin
  if not public.pode_administrar() then
    raise exception 'NAO_AUTORIZADO';
  end if;
  if char_length(v_titulo) not between 1 and 120 or p_minutos is null or p_minutos not between 0 and 1440 then
    raise exception 'CARGA_INVALIDA';
  end if;
  update public.atividades_certificado a set titulo = v_titulo, minutos = p_minutos where a.id = p_id;
  if not found then
    raise exception 'ATIVIDADE_INEXISTENTE';
  end if;
end $$;

