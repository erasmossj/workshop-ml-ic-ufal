-- Configuração única do evento (linha singleton). Horários com fuso explícito.
create table public.config_evento (
  id boolean primary key default true check (id),
  inscricoes_inicio timestamptz not null,
  inscricoes_fim timestamptz not null,
  submissoes_inicio timestamptz not null,
  submissoes_fim timestamptz not null,
  limite_diario_email integer not null default 450 check (limite_diario_email > 0),
  constraint janelas_validas check (
    inscricoes_inicio < inscricoes_fim and submissoes_inicio < submissoes_fim
  )
);

create table public.minicursos (
  id smallint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  titulo text not null,
  vagas integer check (vagas >= 0), -- null = vagas ainda não definidas (inscrição fechada)
  ocupadas integer not null default 0 check (ocupadas >= 0),
  constraint ocupadas_ate_vagas check (vagas is null or ocupadas <= vagas)
);

create sequence public.numero_inscricao_seq;

create table public.participantes (
  id uuid primary key default gen_random_uuid(),
  numero text not null unique
    default 'ICML26-' || lpad(nextval('public.numero_inscricao_seq')::text, 4, '0'),
  nome text not null check (char_length(nome) between 3 and 120),
  cpf text not null check (cpf ~ '^[0-9]{11}$'),
  email text not null check (email = lower(btrim(email)) and char_length(email) <= 254),
  instituicao text check (char_length(instituicao) <= 160),
  consentimento_em timestamptz not null default now(),
  criada_em timestamptz not null default now(),
  cancelada_em timestamptz
);
-- E-mail único; CPF pode repetir (correção de inscrição feita com e-mail errado).
create unique index participantes_email_key on public.participantes (email);

create table public.inscricoes_minicurso (
  participante_id uuid not null references public.participantes (id) on delete cascade,
  minicurso_id smallint not null references public.minicursos (id),
  cpf text not null,
  criada_em timestamptz not null default now(),
  primary key (participante_id, minicurso_id),
  -- O mesmo CPF não ocupa duas vagas no mesmo minicurso.
  constraint cpf_unico_por_minicurso unique (cpf, minicurso_id)
);

create type public.status_trabalho as enum ('pendente', 'rejeitado', 'aprovado_poster', 'aprovado_oral');
create type public.nivel_premio as enum ('graduacao', 'mestrado');

create table public.trabalhos (
  id uuid primary key default gen_random_uuid(),
  participante_id uuid not null unique references public.participantes (id) on delete cascade,
  titulo text not null check (char_length(titulo) between 3 and 250),
  autores text not null check (char_length(autores) between 3 and 600),
  resumo text not null check (char_length(resumo) between 10 and 1500),
  premio boolean not null default false,
  nivel public.nivel_premio,
  pdf_path text, -- preenchido após o upload (URL assinada)
  status public.status_trabalho not null default 'pendente',
  criado_em timestamptz not null default now(),
  constraint nivel_quando_premio check (not premio or nivel is not null)
);

create table public.email_outbox (
  id bigint generated always as identity primary key,
  participante_id uuid not null references public.participantes (id) on delete cascade,
  tipo text not null check (tipo in ('confirmacao', 'certificado')),
  status text not null default 'pendente' check (status in ('pendente', 'enviando', 'enviado', 'falhou')),
  tentativas smallint not null default 0,
  ultimo_erro text,
  criado_em timestamptz not null default now(),
  enviado_em timestamptz
);
create index email_outbox_fila_idx on public.email_outbox (status, criado_em);

-- Allowlist do painel. O login (magic link) só existe para contas criadas pela organização.
create table public.organizadores (
  email text primary key check (email = lower(btrim(email))),
  criado_em timestamptz not null default now()
);

-- RLS deny-by-default: nenhuma policy para anon/authenticated.
