-- Usada pela fila de e-mail (send-emails): CPF completo só aqui, para o PDF.
create function public.certificado_por_numero(p_numero text)
returns table (numero text, nome text, cpf text, minutos integer, codigo text, emitido_em timestamptz)
language sql stable security definer set search_path = '' as $$
  select p.numero, p.nome, p.cpf, c.minutos, c.codigo, c.emitido_em
    from public.participantes p
    join public.certificados c on c.participante_id = p.id
   where p.numero = upper(btrim(coalesce(p_numero, ''))) and p.cancelada_em is null
$$;

-- Usada pela Edge Function `certificado` (Turnstile + limite por origem antes de chegar aqui).
create function public.certificado_para_download(p_email text, p_numero text)
returns table (numero text, nome text, cpf text, minutos integer, codigo text, emitido_em timestamptz)
language sql stable security definer set search_path = '' as $$
  select p.numero, p.nome, p.cpf, c.minutos, c.codigo, c.emitido_em
    from public.participantes p
    join public.certificados c on c.participante_id = p.id
   where p.email = lower(btrim(coalesce(p_email, '')))
     and p.numero = upper(btrim(coalesce(p_numero, '')))
     and p.cancelada_em is null
$$;

-- Pública: confere a autenticidade pelo código (100 bits aleatórios: enumerar é inviável).
create function public.validar_certificado(p_codigo text)
returns table (nome text, cpf_mascarado text, minutos integer, emitido_em timestamptz)
language plpgsql stable security definer set search_path = '' as $$
declare
  -- Crockford: O vira 0; I e L viram 1; espaços e hífens são ignorados.
  v text := translate(upper(regexp_replace(coalesce(p_codigo, ''), '[^0-9A-Za-z]', '', 'g')), 'OIL', '011');
begin
  if char_length(v) <> 20 then
    return;
  end if;
  return query
  select p.nome, public.mascarar_cpf(p.cpf), c.minutos, c.emitido_em
    from public.certificados c
    join public.participantes p on p.id = c.participante_id
   where c.codigo = substr(v, 1, 5) || '-' || substr(v, 6, 5) || '-' || substr(v, 11, 5) || '-' || substr(v, 16, 5);
end $$;

