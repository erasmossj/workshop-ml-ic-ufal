-- 100 bits aleatórios em base32 de Crockford (sem I, L, O, U): XXXXX-XXXXX-XXXXX-XXXXX.
create function public.novo_codigo_certificado() returns text
language plpgsql volatile set search_path = '' as $$
declare
  v_alfabeto constant text := '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
  v_bytes bytea := extensions.gen_random_bytes(13);
  v_bits text := '';
  v_codigo text := '';
begin
  for i in 0..12 loop
    v_bits := v_bits || (get_byte(v_bytes, i)::bit(8))::text;
  end loop;
  for i in 0..19 loop
    v_codigo := v_codigo || substr(v_alfabeto, (substr(v_bits, i * 5 + 1, 5)::bit(5))::integer + 1, 1);
  end loop;
  return substr(v_codigo, 1, 5) || '-' || substr(v_codigo, 6, 5) || '-' || substr(v_codigo, 11, 5) || '-'
      || substr(v_codigo, 16, 5);
end $$;

-- Emite para quem tem horas e ainda não tem certificado; põe o e-mail na fila (teto diário vale).
create function public.admin_liberar_certificados() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_emitidos integer;
begin
  if not public.pode_administrar() then
    raise exception 'NAO_AUTORIZADO';
  end if;
  if not exists (select 1 from public.config_certificado c
                  where c.id and c.template_path is not null and c.campos is not null) then
    raise exception 'MODELO_INCOMPLETO';
  end if;
  perform pg_advisory_xact_lock(hashtext('public.admin_liberar_certificados'));

  with candidatos as (
    select p.id, public.horas_participante(p.id) as minutos
      from public.participantes p
     where p.cancelada_em is null
       and not exists (select 1 from public.certificados c where c.participante_id = p.id)
  ), novos as (
    insert into public.certificados (participante_id, codigo, minutos)
    select c.id, public.novo_codigo_certificado(), c.minutos from candidatos c where c.minutos > 0
    returning participante_id
  ), fila as (
    insert into public.email_outbox (participante_id, tipo)
    select n.participante_id, 'certificado' from novos n
    returning 1
  )
  select count(*) into v_emitidos from fila;

  return jsonb_build_object('emitidos', v_emitidos);
end $$;

create function public.admin_resumo_certificados() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.pode_administrar() then
    raise exception 'NAO_AUTORIZADO';
  end if;
  return jsonb_build_object(
    'modelo_configurado', (select c.template_path is not null and c.campos is not null
                             from public.config_certificado c where c.id),
    'com_horas', (select count(*) from public.participantes p
                   where p.cancelada_em is null and public.horas_participante(p.id) > 0),
    'emitidos', (select count(*) from public.certificados),
    'emails_pendentes', (select count(*) from public.email_outbox o
                          where o.tipo = 'certificado' and o.status in ('pendente', 'enviando')),
    'emails_enviados', (select count(*) from public.email_outbox o
                         where o.tipo = 'certificado' and o.status = 'enviado'),
    'emails_falhou', (select count(*) from public.email_outbox o
                       where o.tipo = 'certificado' and o.status = 'falhou')
  );
end $$;

